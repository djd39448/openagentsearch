# 7. manifest sanity on the fixture.
# ---------------------------------------------------------------------------------------------


def test_manifest_sanity_gap_intervals_and_derived_counts() -> None:
    manifest = _committed_manifest()
    rooms = {room["room"]: room for room in manifest["rooms"]}

    alpha = rooms["alpha"]
    assert alpha["gap_intervals"] == [[103, 104], [109, 111]]
    assert alpha["missing_within_range"] == alpha["seq_range"] - alpha["distinct_seq"]

    bravo = rooms["bravo"]
    assert bravo["signed_rows"] == bravo["rows"] - 1

    assert manifest["totals"]["malformed_lines"] == 1
    # the sender shared between alpha and bravo is counted exactly once in the union.
    assert manifest["totals"]["distinct_senders"] == (
        alpha["distinct_senders"] + bravo["distinct_senders"] - 1
    )
